/** 校验标题安全区后发送坐标输入，避免 DOM 点击绕过原生窗口按钮的命中范围。 */
async function previewCoordinateAction(label) {
  const selector = `.media-dialog button[aria-label="${label}"]`
  await waitFor(`!!document.querySelector(${JSON.stringify(selector)}) && !document.querySelector(${JSON.stringify(selector)}).disabled`, `预览坐标操作：${label}`)
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>resolve(true)))')
  const bounds = await evaluate(`(() => {const button=document.querySelector(${JSON.stringify(selector)}),rect=button.getBoundingClientRect(),bar=document.querySelector('.topbar').getBoundingClientRect();return {left:rect.left,right:rect.right,top:rect.top,bottom:rect.bottom,x:Math.round(rect.left+rect.width/2),y:Math.round(rect.top+rect.height/2),titlebarBottom:bar.bottom,width:innerWidth,height:innerHeight}})()`)
  assert.ok(bounds.top >= bounds.titlebarBottom && bounds.left >= 0 && bounds.right <= bounds.width && bounds.bottom <= bounds.height, `${label} 完整位于原生标题区之外`)
  window.webContents.sendInputEvent({ type: 'mouseMove', x: bounds.x, y: bounds.y })
  window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, x: bounds.x, y: bounds.y })
  window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, x: bounds.x, y: bounds.y })
  assert.equal(window.isDestroyed(), false, `${label} 不能销毁应用窗口`)
}
/** 隐藏验收窗口用实际命中元素和坐标派发外点，不抢占用户窗口焦点。 */
async function clickPagePoint(x, y) {
  await evaluate(`(() => {if(!document.elementFromPoint(${x},${y}))throw new Error('外点未命中页面');return true})()`)
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>resolve(true)))')
  // 完整鼠标序列同时触发组件库的按下、松开与外点判定。
  window.webContents.sendInputEvent({ type: 'mouseMove', x, y })
  window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, x, y })
  window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, x, y })
}
/** Escape 从当前焦点冒泡，与真实键盘使用相同的捕获和关闭顺序。 */
async function pressEscape() {
  await evaluate(`(document.activeElement||document.body).dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',code:'Escape',bubbles:true,cancelable:true}))`)
}
async function setValue(selector, value) {
  await evaluate(`(() => { const item=document.querySelector(${JSON.stringify(selector)}); if(!item) throw new Error('找不到输入控件'); item.value=${JSON.stringify(value)}; item.dispatchEvent(new Event('input',{bubbles:true})); item.dispatchEvent(new Event('change',{bubbles:true})); })()`)
}

/** 对可见组件发送实际坐标点击，让浮层关闭与焦点逻辑一同执行。 */
async function clickControl(selector) {
  await waitFor(`!!document.querySelector(${JSON.stringify(selector)})`, '等待组件可操作')
  const point = await evaluate(`(() => {const item=document.querySelector(${JSON.stringify(selector)});item.scrollIntoView({block:'nearest'});const rect=item.getBoundingClientRect();return {x:Math.round(rect.left+rect.width/2),y:Math.round(rect.top+rect.height/2),width:rect.width,height:rect.height}})()`)
  assert.ok(point.width > 0 && point.height > 0, '组件必须可见后再点击')
  window.webContents.sendInputEvent({ type: 'mouseMove', x: point.x, y: point.y })
  window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, x: point.x, y: point.y })
  window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, x: point.x, y: point.y })
}

async function chooseSelect(selector, value, minimumOptions = 1) {
  await clickControl(`${selector} [role="combobox"]`)
  await waitFor(`[...document.querySelectorAll('[role="option"][data-key]')].filter(item=>item.getClientRects().length).length>=${minimumOptions}`, '下拉选项完整展示')
  await clickControl(`[role="option"][data-key=${JSON.stringify(value)}]`)
  await waitFor(`document.querySelector(${JSON.stringify(selector)})?.getAttribute('data-value')===${JSON.stringify(value)}`, '选择实际业务值')
}

/** 日期输入由真实键盘确认，调用组件的格式与边界校验。 */
async function fillDate(selector, value) {
  await clickControl(selector)
  window.webContents.focus()
  await evaluate(`(() => {const input=document.querySelector(${JSON.stringify(selector)});input.focus();input.select()})()`)
  await window.webContents.insertText(value)
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Tab' })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Tab' })
  await evaluate(`document.querySelector(${JSON.stringify(selector)}).blur()`)
  const state = await evaluate(`(() => {const input=document.querySelector(${JSON.stringify(selector)});return {input:input.value,model:input.closest('.ui-date-picker').dataset.value,valid:input.checkValidity(),active:document.activeElement?.outerHTML.slice(0,300)}})()`)
  assert.equal(state.input, value, `真实日期输入必须写入预期值：${JSON.stringify(state)}`)
  assert.equal(state.model, value, `真实日期输入必须提交组件值：${JSON.stringify(state)}`)
}
