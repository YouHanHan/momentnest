async function evaluate(code) {
  try { return await window.webContents.executeJavaScript(code) }
  catch(error) { throw new Error(`界面脚本失败：${code}\n${errors.slice(-3).join('\n')}`,{cause:error}) }
}
async function waitFor(code, label, timeout = 15000) {
  const until = Date.now() + timeout
  while (Date.now() < until) {
    if (await evaluate(code)) return
    await new Promise(resolveWait => setTimeout(resolveWait, 60))
  }
  const notice = await evaluate('document.querySelector(".family-notice,.notice")?.textContent || ""')
  throw new Error(`${label} 未通过。${notice}`)
}
async function clickText(text, selector = 'button') {
  await waitFor(`[...document.querySelectorAll(${JSON.stringify(selector)})].filter(item=>item.textContent.trim().endsWith(${JSON.stringify(text)})).some(item=>!item.disabled)`, `等待操作按钮：${text}`)
  // 新渲染的操作先完成一帧，避免同毫秒合成点击被 Vue 的新监听器时间检查忽略。
  await evaluate('new Promise(resolve=>requestAnimationFrame(()=>resolve(true)))')
  await evaluate(`(() => { const items = [...document.querySelectorAll(${JSON.stringify(selector)})].filter(item => item.textContent.trim().endsWith(${JSON.stringify(text)})); if (items.length !== 1 || items[0].disabled) throw new Error(${JSON.stringify(`无法点击：${text}`)}); items[0].click(); })()`)
}
